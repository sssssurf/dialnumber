// Independent capture semantics: JavaScript RegExp.exec supplies the prefix
// length and every capture, including unmatched optional groups. Runtime tests
// and the library need neither JavaScript regex nor a network connection.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatMoonBit } from './format-moonbit.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const plans = JSON.parse(fs.readFileSync(path.join(root, 'data/numbering-plans.json')));
const java = JSON.parse(fs.readFileSync(path.join(root, 'data/google-compatibility-corpus.json')));
const q = JSON.stringify;
let seed = 20261107;
let cases = 0;
const lines = ['// Generated by gen-prefix-corpus.mjs; expectations from JS RegExp.exec.', ''];
for (const region of plans.regions.filter(r => r.prefix_transform)) {
  const inputs = new Set(region.types.filter(t => t.example).flatMap(t =>
    [t.example, region.national_prefix + t.example]));
  for (const row of java.rows) {
    if (row[1] === 'phone' && row[5] === region.code) inputs.add(row[8].replace(/\D/g, ''));
  }
  for (let i = 0; i < 24; i++) {
    let digits = '';
    const length = 5 + i % 12;
    for (let j = 0; j < length; j++) {
      seed = seed * 48271 % 2147483647;
      digits += seed % 10;
    }
    inputs.add(digits);
    inputs.add('0' + digits);
  }
  const pattern = region.prefix_parsing;
  const re = new RegExp('^(?:' + pattern + ')');
  lines.push('///|', `test ${q('independent prefix captures: ' + region.code)} {`);
  for (const input of inputs) {
    const found = re.exec(input);
    const call = `match_national_prefix(${q(pattern)}, ${q(input)})`;
    if (!found) lines.push(`  assert_true(${call} is None)`);
    else {
      const captures = ['None', ...found.slice(1).map(v => v === undefined ? 'None' : `Some(${q(v)})`)];
      lines.push('  {', `    let matched = ${call}.unwrap()`,
        `    assert_eq(matched.end, ${found[0].length})`,
        `    assert_eq(matched.captures, [${captures.join(', ')}])`, '  }');
    }
    cases++;
  }
  lines.push('}', '');
}
const output = formatMoonBit(lines.join('\n'));
const target = path.join(root, 'prefix_capture_corpus_wbtest.mbt');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Prefix capture corpus is stale');
} else fs.writeFileSync(target, output);
console.log(`Independent prefix capture oracle: ${cases} cases across 32 transform plans`);
