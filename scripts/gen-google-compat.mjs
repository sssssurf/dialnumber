// Original Google Java library expectations, recorded once and checked offline.
// --jar /path/libphonenumber-9.0.17.jar independently recreates the recording.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { formatMoonBit } from './format-moonbit.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const recording = path.join(root, 'data/google-compatibility-corpus.json');
const jarHash = 'c280b2493de61a070edbc9a83e27023dfd0453cc1295601a48802af907926bcd';
const phones = [['GB','020 7946 0958'],['US','(201) 555-0123'],['JP','090-1234-5678'],
  ['DE','030 123456'],['FR','01 23 45 67 89'],['CN','131 2345 6789'],
  ['AU','02 1234 5678'],['BR','(11) 98765-4321'],
  ...['+80012345678','+80812345678','+870301234567','+878101234567890',
    '+8816123456789','+88213001234','+883510012345','+88812345678901',
    '+979123456789'].map(input=>['',input])];
const traces = [['GB','02079460958'],['US','2015550123'],['US','12015550123'],
  ['US','+442079460958'],['JP','09012345678'],['US','201555012345678']];
const matches = [[1,'2015550123',1,'2015550123','',''],
  [1,'2015550123',44,'2015550123','',''],[1,'2015550123',0,'2015550123','',''],
  [1,'2015550123',1,'5550123','',''],[1,'2015550123',1,'2015550123','42',''],
  [1,'2015550123',1,'2015550123','42','43']];
const requests = [...phones.map(([region,input],i)=>[`phone-${i}`,'phone',region,input]),
  ...traces.map(([region,input],i)=>[`typing-${i}`,'typing',region,input]),
  ...matches.map((row,i)=>[`match-${i}`,'match',...row])];
const index = process.argv.indexOf('--jar');
if (index >= 0) {
  const jar = path.resolve(process.argv[index + 1]);
  if (crypto.createHash('sha256').update(fs.readFileSync(jar)).digest('hex') !== jarHash) {
    throw new Error('Expected the pinned official libphonenumber 9.0.17 jar');
  }
  const scratch = fs.mkdtempSync(path.join(tmpdir(), 'google-phone-oracle-'));
  try {
    const input = path.join(scratch, 'inputs.tsv');
    const output = path.join(scratch, 'outputs.tsv');
    fs.writeFileSync(input, requests.map(row=>row.join('\t')).join('\n')+'\n');
    const result = spawnSync('java', ['--class-path', jar,
      path.join(root,'scripts/ReferenceOracle.java'), input, output], { stdio:'inherit' });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error('Java reference oracle failed');
    const rows = fs.readFileSync(output,'utf8').trimEnd().split(/\r?\n/).map(line=>line.split('\t'));
    fs.writeFileSync(recording,JSON.stringify({
      oracle:{ project:'Google libphonenumber',version:'9.0.17',license:'Apache-2.0',jarSha256:jarHash,
        url:'https://repo.maven.apache.org/maven2/com/googlecode/libphonenumber/libphonenumber/9.0.17/libphonenumber-9.0.17.jar' },
      requests, rows,
    },null,2)+'\n');
  } finally { fs.rmSync(scratch,{recursive:true,force:true}); }
}
const doc = JSON.parse(fs.readFileSync(recording));
const differences = JSON.parse(fs.readFileSync(path.join(root,'data/google-compatibility-differences.json')));
const usedDifferences = new Set();
if (JSON.stringify(doc.requests) !== JSON.stringify(requests)) throw new Error('Java fixture inputs changed; regenerate the recording');
const q = JSON.stringify;
const out = ['// Generated by gen-google-compat.mjs from the original Google Java library.',
  '// Google libphonenumber 9.0.17. No Java runtime is needed by these tests.', ''];
for (const row of doc.rows) {
  const request = requests.find(r=>r[0]===row[0]);
  out.push('///|', `test ${q('original Google Java oracle: '+row[0])} {`);
  if (row[1] === 'phone') {
    const [,,hint,input] = request;
    out.push(`  let p = @dialnumber.parse(${q(input)}, ${q(hint)}).unwrap()`,
      `  assert_eq(@dialnumber.is_valid(p), ${row[2]})`,
      `  assert_eq(@dialnumber.is_possible(p), ${row[3]})`,
      `  assert_eq(@dialnumber.format_e164(p), ${q(row[4])})`,
      `  assert_eq(@dialnumber.region_of_number(p), Some(${q(row[5])}))`,
      `  assert_eq(@dialnumber.number_type(p).unwrap().to_string(), ${q(row[6])})`);
    // Non-geographic network grouping is outside the region-keyed formatting
    // table. Its parsing/validation/type still runs through the original oracle.
    if (hint) out.push(`  assert_eq(@dialnumber.format_international(p), ${q(row[7])})`,
      `  assert_eq(@dialnumber.format_national(p, ${q(hint)}), Some(${q(row[8])}))`);
  } else if (row[1] === 'typing') {
    out.push(`  let f = @dialnumber.AsYouTypeFormatter::new(${q(request[2])})`,
      '  let mismatches : Array[String] = []');
    [...request[3]].forEach((c,i)=>{
      const key = row[0]+'/'+i;
      const difference = differences[key];
      if (difference && (difference.oracle !== row[i+2] || !difference.reason)) throw new Error('Stale Google difference: '+key);
      if (difference) usedDifferences.add(key);
      const wanted = difference?.actual ?? row[i+2];
      out.push(`  let actual_${i} = f.input_digit('${c}')`,
        `  if actual_${i} != ${q(wanted)} { mismatches.push(${q(key+' actual=[')} + actual_${i} + "]") }`);
    });
    out.push('  for mismatch in mismatches { println("JAVA_COMPAT " + mismatch) }',
      '  assert_eq(mismatches.length(), 0)');
  } else {
    const [,,ccA,nnA,ccB,nnB,extA,extB] = request;
    const values = { EXACT_MATCH:'ExactMatch',NSN_MATCH:'NsnMatch',SHORT_NSN_MATCH:'ShortNsnMatch',NO_MATCH:'NoMatch' };
    out.push(`  let a = @dialnumber.PhoneNumber::new(${ccA}, ${q(nnA)}).with_extension(${q(extA)})`,
      `  let b = @dialnumber.PhoneNumber::new(${ccB}, ${q(nnB)}).with_extension(${q(extB)})`,
      `  assert_eq(@dialnumber.is_number_match(a, b), @dialnumber.${values[row[2]]})`);
  }
  out.push('}', '');
}
for (const key of Object.keys(differences)) if (!usedDifferences.has(key)) throw new Error('Unused Google difference: '+key);
const rendered = formatMoonBit(out.join('\n'));
const target = path.join(root,'google_compatibility_test.mbt');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target,'utf8')!==rendered) throw new Error('google_compatibility_test.mbt is stale');
} else fs.writeFileSync(target,rendered);
console.log(`Original Google Java oracle: ${doc.rows.length} scenarios checked/recorded`);

const fence = String.fromCharCode(96).repeat(3);
const report = ['# Direct verification against Google Java libphonenumber', '',
  'This recording executes the **original Google Java libphonenumber 9.0.17**',
  'from its official Maven Central artifact, through scripts/ReferenceOracle.java.',
  'This is separate from the broader libphonenumber-js corpus.', '',
  `Artifact SHA-256: ${jarHash}.`, '',
  '- 17 complete phone scenarios: eight national-input parse/format round trips',
  '  and all nine non-geographic networks. E.164, possibility, validity, region',
  '  and number type agree; regional national/international formatting agrees.',
  '- Six number comparisons use PhoneNumberUtil.isNumberMatch directly and agree,',
  '  including different explicit calling codes, unknown code, short suffix,',
  '  missing extension and conflicting extensions.',
  '- Six original AsYouTypeFormatter traces record every keystroke. Completed',
  '  outputs and digits agree. The following intermediate presentation differences',
  '  remain explicit, with both values retained and tested:', '',
  '| Trace / zero-based step | Java reference | Library |', '| --- | --- | --- |',
  ...Object.entries(differences).map(([key,d])=>`| ${key} | ${JSON.stringify(d.oracle)} | ${JSON.stringify(d.actual)} |`),
  '', 'The library uses the national formatting template earlier in a few NANP',
  'prefixes; Java delays parentheses. Java adds a space after a complete calling',
  'code before the next digit. These are presentation differences, not discarded',
  'digits or a change of telephone destination. This suite does not claim full',
  'global Java parity or network grouping parity for non-geographic formatting.', '',
  '## Reproduce offline', '', fence+'bash',
  'node scripts/gen-google-compat.mjs --check', 'moon test --target wasm-gc', fence, '',
  '## Recreate the reference recording', '',
  'Obtain the [pinned official jar]('+doc.oracle.url+') and use JDK 11 or newer:', '',
  fence+'bash', 'node scripts/gen-google-compat.mjs --jar /path/to/libphonenumber-9.0.17.jar',
  'git diff -- data/google-compatibility-corpus.json google_compatibility_test.mbt', fence, '',
  'The generator verifies the jar checksum before running Java. CI consumes the',
  'committed data and generated MoonBit assertions without installing Java.', '',
].join('\n');
const reportPath = path.join(root, 'docs/google-compatibility.md');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(reportPath,'utf8')!==report) throw new Error('docs/google-compatibility.md is stale');
} else fs.writeFileSync(reportPath, report);
