// Generate/check the calling-code keyed table independently of region metadata.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { formatMoonBit } from './format-moonbit.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const doc = JSON.parse(fs.readFileSync(path.join(root, 'data/non-geographic.json')));
const names = { f:'FixedLine',m:'Mobile',t:'TollFree',p:'PremiumRate',s:'SharedCost',
  v:'Voip',r:'PersonalNumber',u:'Uan',g:'Pager',o:'Voicemail' };
const out = ['// Generated by scripts/gen-non-geo.mjs; do not edit.',
  '// Source: data/non-geographic.json (Apache-2.0).', '', '///|',
  'let non_geo_plans : Array[NonGeoPlan] = ['];
const codes = doc.networks.map(n=>n.calling_code).sort((a,b)=>a-b);
if (JSON.stringify(codes) !== '[800,808,870,878,881,882,883,888,979]') throw new Error('Incomplete network data');
for (const n of doc.networks) {
  out.push('  plan_non_geo(',`    ${n.calling_code},`, `    ${JSON.stringify(n.general)},`, '    [');
  for (const t of n.types) out.push(`      plan_type(${names[t.kind]}, ${JSON.stringify(t.pattern)}, [${t.national.join(', ')}], []),`);
  out.push('    ],', '  ),');
}
out.push(']', '');
const output = formatMoonBit(out.join('\n'));
const target = path.join(root, 'non_geo_data.mbt');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target,'utf8')!==output) throw new Error('non_geo_data.mbt is stale');
  console.log('Non-geographic data checked: nine networks');
} else {
  fs.writeFileSync(target,output);
  console.log('Wrote non_geo_data.mbt');
}
