// Generate a differential corpus for the pattern engine.
//
//   node scripts/gen-corpus.mjs
//
// The expected answer for every case is computed with a JavaScript regular
// expression, i.e. an independent implementation of the same grammar, so this
// test says "our NFA agrees with a regex engine on every published rule", not
// "our engine agrees with itself". Each published example is used once as a
// positive case and once mutated as a negative case.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "data", "numbering-plans.json");
const OUT = path.join(ROOT, "pattern_corpus_test.mbt");

const doc = JSON.parse(fs.readFileSync(DATA, "utf8"));
const re = (p) => new RegExp("^(?:" + p + ")$");
const q = (s) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

const cases = [];
for (const r of doc.regions) {
  for (const t of r.types) {
    if (!t.example) continue;
    cases.push([t.pattern, t.example, `${r.code}/${t.kind}/example`]);
    // One mutation: bump the fourth digit, which lands inside the significant
    // part for almost every plan.
    const chars = [...t.example];
    const at = Math.min(3, chars.length - 1);
    chars[at] = String((Number(chars[at]) + 1) % 10);
    cases.push([t.pattern, chars.join(""), `${r.code}/${t.kind}/mutation`]);
  }
}

const lines = [];
lines.push("// Differential corpus for the pattern engine.");
lines.push("//");
lines.push("// Generated by scripts/gen-corpus.mjs: one positive and one negative case");
lines.push("// per published rule, with the expected answer computed by an independent");
lines.push("// regular-expression engine. A regression in the parser or the NFA shows up");
lines.push("// here as a disagreement with the reference, one rule at a time.");
lines.push("///|");
lines.push('test "the engine agrees with a reference regex engine on every rule" {');
for (const [pattern, text, label] of cases) {
  const expected = re(pattern).test(text);
  lines.push(`  // ${label}`);
  lines.push(`  assert_${expected ? "true" : "false"}(@dialnumber.matches_pattern(${q(pattern)}, ${q(text)}))`);
}
lines.push("}");
lines.push("");

const content = lines.join("\n");
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (current === content) {
  console.log("corpus is up to date");
} else if (process.argv.includes("--check")) {
  console.error("pattern_corpus_test.mbt is out of date: run node scripts/gen-corpus.mjs");
  process.exit(1);
} else {
  fs.writeFileSync(OUT, content);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${content.length} bytes, ${cases.length} cases)`);
}
