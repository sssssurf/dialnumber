// Record an independent oracle once, then regenerate/check MoonBit tests offline.
// node scripts/gen-compat.mjs --oracle /path/to/libphonenumber-js/package
// node scripts/gen-compat.mjs [--check]
// Reference implementation: libphonenumber-js 1.11.20, MAX metadata (MIT).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { formatMoonBit } from './format-moonbit.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const corpusPath = path.join(root, 'data/compatibility-corpus.json');
const exceptionsPath = path.join(root, 'data/compatibility-differences.json');
const metadata = fs.readFileSync(path.join(root, 'data/numbering-plans.json'));
const sourceHash = crypto.createHash('sha256').update(metadata).digest('hex');
const q = JSON.stringify;
const oracleIndex = process.argv.indexOf('--oracle');
if (oracleIndex >= 0) {
  const oracleRoot = path.resolve(process.argv[oracleIndex + 1]);
  const pkg = JSON.parse(fs.readFileSync(path.join(oracleRoot, 'package.json')));
  if (pkg.name !== 'libphonenumber-js' || pkg.version !== '1.11.20') {
    throw new Error('Expected libphonenumber-js 1.11.20');
  }
  const require = createRequire(import.meta.url);
  const lib = require(path.join(oracleRoot, 'max/index.cjs'));
  const data = JSON.parse(metadata);
  const rows = [];
  function record(id, input, hint = '', formatting = false) {
    const phone = lib.parsePhoneNumberFromString(input, hint || undefined);
    rows.push({ id, input, e164: phone?.number ?? '', valid: phone?.isValid() ?? false,
      possible: phone?.isPossible() ?? false,
      region: phone?.country ?? (phone?.isNonGeographic() ? '001' : ''),
      type: phone?.getType()?.toLowerCase().replaceAll('_', '-') ?? '',
      ...(hint ? { hint } : {}),
      ...(formatting ? { international: phone.formatInternational(),
        national: phone.formatNational() } : {}) });
  }
  for (const region of data.regions) {
    for (const type of region.types) {
      if (!type.example) continue;
      const input = '+' + region.calling_code + type.example;
      record(region.code + ':' + type.kind, input);
      // A deliberately overlong near-miss, judged by the independent oracle.
      record(region.code + ':' + type.kind + ':overlong', input + '0000000000000000');
    }
  }
  for (const input of ['+80012345678', '+80812345678', '+870301234567',
    '+878101234567890', '+8816123456789', '+88213001234', '+883510012345',
    '+88812345678901', '+979123456789']) {
    record('001:' + input, input);
    record('001:' + input + ':short', input.slice(0, -4));
    record('001:' + input + ':overlong', input + '0000000000000000');
  }
  for (const [region, input] of [['GB', '020 7946 0958'], ['US', '(201) 555-0123'],
    ['JP', '090-1234-5678'], ['DE', '030 123456'], ['FR', '01 23 45 67 89'],
    ['CN', '131 2345 6789'], ['AU', '02 1234 5678'], ['BR', '(11) 98765-4321']]) {
    record('format:' + region, input, region, true);
  }
  const traces = [];
  for (const [region, input] of [['GB', '02079460958'], ['US', '2015550123'],
    ['US', '12015550123'], ['US', '+442079460958'], ['JP', '09012345678'],
    ['US', '201555012345678']]) {
    const formatter = new lib.AsYouType(region);
    traces.push({ region, input, output: [...input].map(c => formatter.input(c)) });
  }
  const corpus = { oracle: { package: pkg.name, version: pkg.version, metadata: 'max',
    license: pkg.license,
    sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join(oracleRoot, 'metadata.max.json'))).digest('hex'),
    numberingPlansSha256: sourceHash }, rows, traces };
  fs.writeFileSync(corpusPath, JSON.stringify(corpus, null, 2) + '\n');
  console.log(`Recorded ${rows.length} cases and ${traces.length} typing traces`);
}

const corpus = JSON.parse(fs.readFileSync(corpusPath));
if (corpus.oracle.numberingPlansSha256 !== sourceHash) {
  throw new Error('Numbering-plan metadata changed: regenerate the oracle corpus');
}
const exceptions = JSON.parse(fs.readFileSync(exceptionsPath));
const used = new Set();
const out = ['// Generated by scripts/gen-compat.mjs; do not edit.',
  '// Independent oracle: libphonenumber-js 1.11.20, max metadata.',
  '// All cases remain in the corpus; explained differences are explicit.', ''];
function expected(row, field) {
  const key = row.id + '/' + field;
  const difference = exceptions[key];
  if (!difference) return row[field];
  if (difference.oracle !== row[field] || !difference.reason) throw new Error('Stale difference: ' + key);
  used.add(key);
  return difference.actual;
}
const regions = new Map();
for (const row of corpus.rows) {
  const region = row.id.split(':')[0];
  if (!regions.has(region)) regions.set(region, []);
  regions.get(region).push(row);
}
for (const [region, rows] of regions) {
  out.push('///|', `test ${q('end-to-end oracle: ' + region)} {`, '  let differences : Array[String] = []');
  for (const row of rows) {
    out.push(`  match @dialnumber.parse(${q(row.input)}, ${q(row.hint ?? '')}) {`);
    out.push('    None => {');
    if (row.e164 !== '') out.push(`      differences.push(${q(row.id + '/parse: unexpectedly rejected')})`);
    else out.push('      ()');
    out.push('    }', '    Some(p) => {');
    const fields = [ ['valid', '@dialnumber.is_valid(p)'], ['possible', '@dialnumber.is_possible(p)'],
      ['e164', '@dialnumber.format_e164(p)'] ];
    if (!row.id.endsWith(':overlong') && !row.id.endsWith(':short')) {
      fields.push(['region', '@dialnumber.region_of_number(p).unwrap_or("")']);
      fields.push(['type', 'match @dialnumber.number_type(p) { Some(t) => t.to_string(); None => "" }']);
    }
    if (row.international) fields.push(['international', '@dialnumber.format_international(p)']);
    if (row.national) fields.push(['national', `@dialnumber.format_national(p, ${q(row.region)}).unwrap_or("")`]);
    for (const [field, expression] of fields) {
      // An overlong input is intentionally unparseable to the oracle; our
      // parser accepts its structure, but must reject validity and possibility.
      if (field === 'e164' && row.e164 === '') continue;
      const want = expected(row, field);
      const actual = `(${expression})`;
      out.push(`      if ${actual} != ${q(want)} { differences.push(${q(row.id + '/' + field + ' expected=' + want + ' actual=')} + ${actual}.to_string()) }`);
    }
    out.push('    }', '  }');
  }
  out.push('  for difference in differences { println("COMPAT " + difference) }',
    '  assert_eq(differences.length(), 0)', '}', '');
}
for (const trace of corpus.traces) {
  out.push('///|', `test ${q('oracle typing: ' + trace.region + ' ' + trace.input)} {`,
    `  let formatter = @dialnumber.AsYouTypeFormatter::new(${q(trace.region)})`);
  [...trace.input].forEach((c, i) => {
    out.push(`  assert_eq(formatter.input_digit('${c}'), ${q(trace.output[i])})`);
  });
  out.push('}', '');
}
for (const key of Object.keys(exceptions)) if (!used.has(key)) throw new Error('Unused difference: ' + key);
// Keep the committed generated test compatible with `moon fmt --check`.
const rendered = formatMoonBit(out.join('\n'));
const target = path.join(root, 'compatibility_test.mbt');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== rendered) throw new Error('compatibility_test.mbt is stale');
  console.log(`Compatibility corpus checked: ${corpus.rows.length} cases, ${Object.keys(exceptions).length} field differences`);
} else {
  fs.writeFileSync(target, rendered);
  console.log('Wrote compatibility_test.mbt');
}

const affected = new Set(Object.keys(exceptions).map(k => k.slice(0, k.lastIndexOf('/'))));
const report = [
  '# End-to-end compatibility with libphonenumber-js', '',
  'The oracle is **libphonenumber-js 1.11.20 with max metadata**, not its less',
  'strict default/min bundle and not the original Java libphonenumber runtime.',
  'The library has no runtime dependency on the oracle. Expectations and their',
  'provenance are committed in `data/compatibility-corpus.json`.', '',
  '## Coverage', '',
  `- ${corpus.rows.length} input cases: all 1,132 published regional examples,`,
  '  their overlong near-misses, nine non-geographic networks with short and',
  '  overlong negatives, and eight national-input formatting scenarios.',
  '- Parse → E.164 → possible/valid → region/type; formatting scenarios also',
  '  compare the national and international renderings.',
  '- For deliberately invalid inputs, only rejection by possible/valid is',
  '  compared. The structural parser may accept text that the oracle rejects;',
  '  that does not make the input a valid telephone number.',
  `- ${corpus.traces.length} incremental formatting traces assert every keystroke, including`,
  '  trunk prefixes, NANP prefixes, international input and overflow.', '',
  `Without accounting for known differences, ${corpus.rows.length - affected.size}/${corpus.rows.length}`,
  `cases agree on every compared field. There are **${affected.size} cases / ${Object.keys(exceptions).length} field`,
  'differences**. No differing input is dropped. Tests assert the recorded',
  'library result for each difference and fail if either it or the oracle',
  'expectation changes. This is a bounded comparison, not universal parity.', '',
  '## All known differences', '',
  '| Case/field | Oracle | Library | Reason |',
  '| --- | --- | --- | --- |',
  ...Object.entries(exceptions).map(([key,d])=>`| \`${key}\` | \`${String(d.oracle) || '(none)'}\` | \`${String(d.actual) || '(none)'}\` | ${d.reason} |`),
  '', '## Reproduce', '', 'With Node.js and the project MoonBit toolchain on PATH:', '',
  '```bash', 'node scripts/gen-compat.mjs --check', 'moon test --target wasm-gc', '```', '',
  'To independently recreate the recorded expectations, obtain the pinned npm',
  'package and pass its extracted package directory:', '', '```bash',
  'npm pack libphonenumber-js@1.11.20',
  'tar -xzf libphonenumber-js-1.11.20.tgz',
  'node scripts/gen-compat.mjs --oracle ./package',
  'git diff -- data/compatibility-corpus.json compatibility_test.mbt docs/compatibility.md',
  '```', '', 'The oracle metadata SHA-256 and the numbering-plan source SHA-256 are',
  'recorded. An unused exception or a changed oracle value fails generation.',
  'CI checks the generated tests offline and executes them on every tested target.', '',
  'The original reference project is [Google libphonenumber](https://github.com/google/libphonenumber).',
  'The executable oracle used here is [libphonenumber-js](https://github.com/catamphetamine/libphonenumber-js).', ''
  ,'Additional scenarios execute the original Google Java library directly;',
  'see [google-compatibility.md](google-compatibility.md) for that independent recording.', ''
].join('\n');
const reportPath = path.join(root, 'docs/compatibility.md');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(reportPath, 'utf8') !== report) throw new Error('docs/compatibility.md is stale');
} else {
  fs.writeFileSync(reportPath, report);
}
